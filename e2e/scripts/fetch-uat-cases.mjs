#!/usr/bin/env node
/**
 * Fetch the UAT / functional test-case sheet ("Meera_UAT_and_functional_july2026")
 * and emit e2e/data/uat-cases.mjs — a committed SNAPSHOT that the report sheet's
 * "UAT July 2026" reference tab mirrors.
 *
 * The UAT sheet is the QA team's bug-feedback log (TC-001…, with screenshots and
 * a Dev Status). It is NOT automation coverage; the tab is a reference mirror so
 * the report sheet is the single place to see both automated results and the UAT
 * findings in flight.
 *
 * Run: npm run sheet:uat-fetch
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import dotenv from "dotenv";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "../..");
dotenv.config({ path: path.join(root, ".env") });

const UAT_SHEET_ID =
  process.env.UAT_CASES_SHEET_ID ??
  "1bR1d9NwurDtGvnZ-TvQsRLapaNOlqAx5NexIh01JCVQ";
const UAT_TAB = "UAT July 2026";
const UAT_SOURCE_URL = `https://docs.google.com/spreadsheets/d/${UAT_SHEET_ID}/edit`;
const OUT_FILE = path.join(root, "e2e/data/uat-cases.mjs");
const COLUMN_COUNT = 9;

function b64url(input) {
  return Buffer.from(input)
    .toString("base64")
    .replace(/=/g, "")
    .replace(/\+/g, "-")
    .replace(/\//g, "_");
}

function loadCredentials() {
  const raw = process.env.GOOGLE_SERVICE_ACCOUNT_JSON;
  if (!raw) throw new Error("Set GOOGLE_SERVICE_ACCOUNT_JSON in .env");
  if (raw.trim().startsWith("{")) return JSON.parse(raw);
  return JSON.parse(fs.readFileSync(path.resolve(root, raw), "utf8"));
}

async function getAccessToken(credentials) {
  const now = Math.floor(Date.now() / 1000);
  const header = b64url(JSON.stringify({ alg: "RS256", typ: "JWT" }));
  const payload = b64url(
    JSON.stringify({
      iss: credentials.client_email,
      scope: "https://www.googleapis.com/auth/spreadsheets.readonly",
      aud: "https://oauth2.googleapis.com/token",
      iat: now,
      exp: now + 3600,
    }),
  );
  const signInput = `${header}.${payload}`;
  const sign = crypto.sign("RSA-SHA256", Buffer.from(signInput), credentials.private_key);
  const jwt = `${signInput}.${b64url(sign)}`;
  const res = await fetch("https://oauth2.googleapis.com/token", {
    method: "POST",
    headers: { "Content-Type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams({ grant_type: "urn:ietf:params:oauth:grant-type:jwt-bearer", assertion: jwt }),
  });
  if (!res.ok) throw new Error(`Token exchange failed: ${res.status} ${await res.text()}`);
  return (await res.json()).access_token;
}

async function readUatTab(token) {
  const range = "Sheet1!A1:I1000";
  const res = await fetch(
    `https://sheets.googleapis.com/v4/spreadsheets/${UAT_SHEET_ID}/values/${encodeURIComponent(range)}?valueRenderOption=FORMATTED_VALUE`,
    { headers: { Authorization: `Bearer ${token}` } },
  );
  if (!res.ok) {
    throw new Error(`Failed to read UAT sheet: ${res.status} ${await res.text()}`);
  }
  return (await res.json()).values ?? [];
}

function cleanCell(v) {
  return String(v ?? "").replace(/\r\n/g, "\n").trim();
}

function main() {
  const creds = loadCredentials();
  getAccessToken(creds)
    .then(async (token) => {
      const rows = await readUatTab(token);
      if (rows.length < 2) {
        throw new Error(`UAT sheet returned ${rows.length} rows — expected a header + data`);
      }

      const header = rows[0].map(cleanCell).slice(0, COLUMN_COUNT);
      const cases = rows
        .slice(1)
        .filter((r) => cleanCell(r[0] ?? "") !== "")
        .map((r) => {
          const cells = [];
          for (let i = 0; i < COLUMN_COUNT; i++) cells.push(cleanCell(r[i] ?? ""));
          return cells;
        });

      const body = `/**
 * UAT / functional test-case reference ("Meera_UAT_and_functional_july2026").
 *
 * Generated by: npm run sheet:uat-fetch
 * Source sheet: ${UAT_SHEET_ID}
 * This is a committed SNAPSHOT mirrored onto the report sheet's "${UAT_TAB}"
 * reference tab. Regenerate whenever the UAT sheet is updated.
 * Do NOT hand-edit — run the fetch script instead.
 */
export const UAT_TAB = ${JSON.stringify(UAT_TAB)};
export const UAT_SOURCE_URL = ${JSON.stringify(UAT_SOURCE_URL)};
export const UAT_HEADER = ${JSON.stringify(header)};
export const UAT_CASES = ${JSON.stringify(cases, null, 2)};
`;
      fs.writeFileSync(OUT_FILE, body);
      console.log(`  ${UAT_TAB}: ${cases.length} case(s) from ${UAT_SHEET_ID}`);
      console.log(`Wrote ${cases.length} UAT cases → ${path.relative(root, OUT_FILE)}`);
    })
    .catch((err) => {
      console.error("[fetch-uat-cases] Failed:", err.message);
      process.exit(1);
    });
}

main();
